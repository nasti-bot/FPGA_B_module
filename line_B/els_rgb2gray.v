// ============================================
// 模块：rgb2gray
// 功能：彩色图(RGB888) 转灰度，公式 Y = (77R + 150G + 29B) / 256
// 输入：R、G、B（各 8 位，0~255）
// 输出：Y（8 位灰度，0~255）
// 说明：除以 256 = 右移 8 位，硬件免费；
//       绿色权重最大(150)，因为人眼对绿最敏感
// ============================================
module rgb2gray(
    input  wire [7:0] R,   // 红
    input  wire [7:0] G,   // 绿
    input  wire [7:0] B,   // 蓝
    output wire [7:0] Y    // 亮度(灰度)
);

    assign Y = (77*R + 150*G + 29*B) >> 8;

endmodule
