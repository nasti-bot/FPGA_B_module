// ============================================
// 模块：shape_class
// 功能：形状分类 —— 用填充率 + 最小面积判断圆/矩形/都不是
// 输入：area（面积）、W（宽）、H（高）
// 输出：shape（2位：00=都不是，01=圆，10=矩形）
// 说明：
//   1. 最小面积过滤：面积太小（噪点团）直接判「都不是」，
//      解决"什么都没有也显示矩形"（单个噪点填充率=1 被误判矩形）
//   2. 填充率判据（分数近似，移位+加法无乘法器）：
//      矩形 = 填充率 > 0.875（7/8）
//      圆   = 填充率 0.625~0.8125（5/8 ~ 13/16）
//      中间 0.8125~0.875 是死区，两者都不判（增加区别度）
//   3. 离散圆实际填充率约 0.59~0.77，正方形=1.0
// ============================================
module shape_class #(
    parameter MIN_AREA = 100    // 最小面积：小于它的都判「都不是」（过滤噪点团）
)(
    input  wire [15:0] area,
    input  wire [7:0]  W,
    input  wire [7:0]  H,
    output reg  [1:0]  shape   // 00=都不是 01=圆 10=矩形
);

    // 外接框面积
    wire [15:0] box = W * H;

    // 分数比较（避免除法）：
    //   area*8  > box*7    → 填充率 > 0.875 → 矩形
    //   area*8  > box*5    → 填充率 > 0.625
    //   area*16 < box*13   → 填充率 < 0.8125
    wire [18:0] area8  = area << 3;
    wire [18:0] box7   = (box << 3) - box;
    wire [18:0] box5   = (box << 2) + box;
    wire [19:0] area16 = area << 4;
    wire [19:0] box13  = (box << 3) + (box << 2) + box;

    always @(*) begin
        if (area < MIN_AREA)
            shape = 2'b00;              // 太小 → 都不是（噪点团）
        else if (area8 > box7)
            shape = 2'b10;              // 填充率 > 0.875 → 矩形
        else if (area8 > box5 && area16 < box13)
            shape = 2'b01;              // 0.625~0.8125 → 圆
        else
            shape = 2'b00;              // 死区或其他 → 都不是
    end

endmodule
